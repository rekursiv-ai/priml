def _name_wandb_runs(config: TrainLoop.Config) -> None:
    """Name each unnamed W&B run after its experiment and seed, grouped by experiment."""
    name = config.experiment_name
    if config.seed is not None:
        name = f"{name}-s{config.seed}"
    for tracker in _wandb_trackers(config.tracker):
        tracker.name = tracker.name or name
        tracker.group = tracker.group or config.experiment_name


def _wandb_trackers(tracker: object) -> Iterator[WandbTracker.Config]:
    """Yield every W&B tracker config under ``tracker``."""
    if isinstance(tracker, WandbTracker.Config):
        yield tracker
    elif isinstance(tracker, TrackerList.Config):
        for child in tracker.trackers.values():
            yield from _wandb_trackers(child)
    elif isinstance(tracker, NanochatSeries.Config | AsyncTracker.Config):
        yield from _wandb_trackers(tracker.tracker)
