def nanochat_trackers() -> NanochatSeries.Config:
    """Log nanochat's series to W&B, and the eval and ``val/`` scores to files.

    Returns:
      config: ``eval/*`` to ``metrics.json``, ``val/*`` to ``val.json``, and
        everything to W&B project ``craftax-world-model`` off the training thread.

    """
    val = FileTracker.Config()
    val.working_dir = "/val.json"
    val.capture_prefix = "val/"
    dashboard = WandbTracker.Config()
    dashboard.project = "craftax-world-model"
    wandb = AsyncTracker.Config()
    wandb.tracker = dashboard
    trackers = TrackerList.Config()
    trackers.trackers = {"metrics": FileTracker.Config(), "val": val, "wandb": wandb}
    config = NanochatSeries.Config()
    config.tracker = trackers
    return config


class WorldModelLoop(TrainLoop):
    """A training loop over the replay stream, scored in the natural mix.

    The stream's ``eval_sampler.counts`` -- the validation split's natural
    decisions per stratum, known only once its index is read -- are handed to
    every ``CraftaxBitsPerByte`` here, which then reports ``bpb_natural`` and
    ``nats_per_decision_natural``, the design's primary metric: natural over
    ``data.EvalSpans``, and only reweighted between strata over the default
    stratified windows. When the stream has ``train_spans``, every evaluation
    also scores them with a second set of the same metrics, in the training
    split's natural mix, so the train-validation gap is logged beside
    validation.
    """

    class Config(
        Makes["WorldModelLoop"],
        TrainLoop.Config[WorldModelTrainStep.Config, ReplayStream.Config],
    ):
        """A loop with the world-model step and the replay stream in place."""

        step: WorldModelTrainStep.Config = field(
            default_factory=WorldModelTrainStep.Config,
        )
        """Model, optimization, and the evaluation scorer."""

        dataset: ReplayStream.Config = field(default_factory=ReplayStream.Config)
        """Stratified windows of a named corpus."""

        tracker: Makeable[TrackerProtocol] | None = field(
            default_factory=nanochat_trackers,
        )
        """nanochat's series to files and W&B."""

        @override
        def finalize(self) -> Self:
            _name_wandb_runs(self)
            return super().finalize()

    def __init__(self, config: Config) -> None:
        # The sampler keys each micro-batch by (step, micro-step), so it must count
        # micro-batches per update exactly as the step accumulates them.
        if config.dataset.micro_batches_per_step != config.step.accumulate_grad_batches:
            raise ValueError(
                f"dataset.micro_batches_per_step={config.dataset.micro_batches_per_step}"
                " must equal step.accumulate_grad_batches="
                f"{config.step.accumulate_grad_batches}.",
            )
        super().__init__(config)
        dataset = self.dataset
        assert isinstance(dataset, ReplayStream)
        self.metrics_train_split = (
            {name: metric.make() for name, metric in config.metrics_eval.items()}
            if dataset.train_spans is not None
            else {}
        )
        """The same metrics over ``dataset.train_spans``; empty without them."""
        for metrics, sampler in (
            (self.metrics_eval, dataset.eval_sampler),
            (self.metrics_train_split, dataset.train_sampler),
        ):
            for metric in metrics.values():
                if isinstance(metric, CraftaxBitsPerByte):
                    metric.natural_decisions = sampler.counts.double()

    @override
    def eval(self) -> dict[str, object]:
        """Score validation, then the training split's spans under ``train_split_``.

        Returns:
          metrics: The loop's evaluation, plus each of its keys over
            ``dataset.train_spans`` prefixed ``train_split_``, when configured.

        """
        scores = super().eval()
        if not self.metrics_train_split:
            return scores
        dataset = self.dataset
        assert isinstance(dataset, ReplayStream)
        held, self.metrics_eval = self.metrics_eval, self.metrics_train_split
        try:
            with dataset.training_split():
                fitted = super().eval()
        finally:
            self.metrics_eval = held
        return scores | {f"train_split_{key}": value for key, value in fitted.items()}


def exp000() -> WorldModelLoop.Config:
    """Train the base model: the hierarchical model and its recipe for 50M decisions.

    Encoder 4 x 512, global transformer 20 x 1152 (GQA 9:3, RoPE 500,000, FA4
    varlen within episodes), local decoder 4 x 512 with cross-attention, tied
    461-row table; modality-mean loss with z-loss 1e-5. Muon (Moonlight RMS
    matching) on hidden matrices, AdamW (0.9, 0.95) on tables, heads, and
    scales, peak rate 3e-4, clip 1.0, warmup-stable-decay. BF16 autocast,
    ``torch.compile``, DDP on 8 GPUs, one 8,192-position window each.

    Hypothesis:
      The established open-model decoder recipe (Qwen3, Llama 3, OLMo 2,
      SmolLM3), applied to a hierarchical tokenization of Craftax frames,
      trains stably and beats the trivial baselines on every modality, which
      is the bar each later fork must clear.

    References:
      https://arxiv.org/abs/2508.06471
        GLM-4.5 technical report, section 2.4: Muon for hidden matrices.
      https://arxiv.org/abs/2502.16982
        Liu et al. 2025. Muon is scalable for LLM training (Moonlight).
      https://huggingface.co/blog/smollm3
        SmolLM3: warmup-stable-decay with a linear decay to zero.

    Results:
      TBD.

    """
    cfg = WorldModelLoop.Config()
    cfg.study_name = "craftax-world-model"
    cfg.experiment_name = "exp000"

    model = cfg.step.model
    assert isinstance(model, WorldModel.Config)
    block = model.transformer.block
    assert isinstance(block, TransformerBlock.Config)
    assert isinstance(block.attn, VarlenAttention.Config)
    block.attn.attn_kernel = Flash4Varlen.Config()

    runtime = cfg.runtime = MultiProcess.Config()
    runtime.device = "cuda"
    runtime.mesh_topology = {"dp": 8, "pp": 1, "tp": 1}
    cfg.step.parallelism = DataParallel.Config()
    cfg.dataset.device = "cuda"

    # One window per GPU per step: 8 windows, about 32,760 decisions.
    decisions_per_step = runtime.mesh_topology["dp"] * cfg.dataset.t_g // 2
    cfg.max_steps = cfg.step.train_budget_steps = BASE_DECISIONS // decisions_per_step
    schedule = cfg.step.lr_schedule = PartialConfig(wsd, decay=0.1)
    schedule.warmup = min(0.1, WARMUP_STEPS / cfg.max_steps)

    cfg.metrics_eval["val"] = CraftaxBitsPerByte.Config()
    # Six evaluations of eight micro-batches per rank, about 2% of the run.
    cfg.num_steps_eval = 250
    cfg.eval_every_epoch = False
    return cfg


def exp001() -> WorldModelLoop.Config:
    """exp000 on one GPU: the same 8-window update, accumulated.

    One H200 instead of an 8-GPU node. One process draws every window of an
    update, as accumulated micro-batches instead of data-parallel ranks, and
    scores as many validation windows as exp000's eight ranks together, 64 of
    8,192 positions. They are not exp000's windows: the validation key names
    the rank, so only rank 0's first eight are shared. Model, optimizer,
    schedule, batch, and budget are exp000's. Each local decoder block
    recomputes its activations in backward, since storing them ran out of
    memory (below).

    Hypothesis:
      Accumulation reproduces exp000's update: each micro-batch's objective is
      divided by the micro-batch count before its backward, as DDP averages
      gradients over ranks, so the updates and the schedule are unchanged and
      only wall time grows, by about the GPU count.

    References:
      https://pytorch.org/docs/stable/notes/ddp.html
        DDP averages gradients over ranks; accumulation divides each
        micro-batch's objective by the micro-batch count to match.

    Results:
      On one H200, recomputing these same blocks through priml's selective
      wrapper: an update of 32,768 decisions takes 4.08 s on synthetic windows
      and 4.14 s on an earlier capture's, 7,900 decisions/s at 24.1% MFU and
      91 GB allocated; the block flag measured 4.17 s. Global FA4 attention is
      2.9% of an update, the optimizer 0.7%, and the GPU idles 1.3%. Launch to
      the first update took 87 s, then 68 s to recompile for the second
      micro-batch's frame count.

      An 84-minute pilot on a 53.8M-decision corpus of that earlier capture
      (37.5M decisions trained) stopped by the clock at update 1,146 of 1,525,
      before the decay. Validation bpb fell
      0.158, 0.0141, 0.0104, 0.0098, 0.0095 at updates 250 to 1,146, against
      zstd -19's 0.108 on the same records, and every modality fell. Losses
      stayed finite, the gradient norm fell from 279 to 0.85 (55% of updates
      clipped), and the max attention logit bound stayed under 14. The
      50M-decision run is not measured yet.

    """
    cfg = exp000()
    cfg.experiment_name = "exp001"
    runtime = cfg.runtime
    assert isinstance(runtime, MultiProcess.Config)
    ranks = runtime.mesh_topology["dp"]
    cfg.runtime = SingleProcess.Config(device="cuda")
    cfg.step.parallelism = NoParallel.Config()
    accumulate = ranks // cfg.dataset.windows
    cfg.step.accumulate_grad_batches = cfg.dataset.micro_batches_per_step = accumulate
    validation = cfg.dataset.validation
    assert isinstance(validation, StratifiedWindows.Config)
    validation.batches *= accumulate
    # Storing every activation of one 8,192-position window peaked at 141 GB of
    # an H200's 143 and ran out of memory under the default allocator.
    model = cfg.step.model
    assert isinstance(model, WorldModel.Config)
    assert isinstance(model.decoder.stack.block, DecoderBlock.Config)
    model.decoder.stack.block.checkpoint = True
    return cfg


def exp002() -> WorldModelLoop.Config:
    """exp001 with 16,384-position windows, 4 per update: the context sweep's value.

    Twice the context at equal decisions per update: half as many windows,
    each twice as long, so the step count, the schedule, and the count of
    validation positions stay exp001's. The validation windows themselves
    differ: each starts up to ``t_g // 2`` decisions before its anchor, and
    there are half as many anchors.

    Hypothesis:
      At 8,192 positions a window holds about 4,095 decisions, less than the
      capture policy's mean episode of 4,216, so most windows cut an episode
      and later decisions condition on a truncated history. 16,384 positions
      hold a whole mean episode; if earlier events of an episode inform later
      frames, validation NLL falls, for about 7.5% more attention FLOPs per
      decision before episode masking.

    References:
      https://arxiv.org/abs/2001.08361
        Kaplan et al. 2020. Scaling laws for neural language models: loss
        falls with context while earlier tokens still inform later ones.

    Results:
      On one H200, on an earlier capture's windows: an update of 32,768
      decisions takes 4.53 s, 7,230 decisions/s at 22.0% MFU, peaking at
      100 GB. Validation NLL is not measured yet.

    """
    cfg = exp001()
    cfg.experiment_name = "exp002"
    cfg.dataset.t_g *= 2
    cfg.step.accumulate_grad_batches = cfg.dataset.micro_batches_per_step = (
        cfg.step.accumulate_grad_batches // 2
    )
    validation = cfg.dataset.validation
    assert isinstance(validation, StratifiedWindows.Config)
    validation.batches //= 2
    # A window holds twice the frames, and recomputing only the decoder blocks
    # ran out of memory on an H200.
    model = cfg.step.model
    assert isinstance(model, WorldModel.Config)
    assert isinstance(model.encoder, FrameEncoder.Config)
    assert isinstance(model.encoder.stack.block, TransformerBlock.Config)
    model.encoder.stack.block.checkpoint = True
    return cfg


def exp010() -> WorldModelLoop.Config:
    """exp002 as the tuning base: its measured speed settings, natural validation.

    Every later fork is timed and scored against this one, so it gathers
    the changes meant to leave the loss curve alone:

    - Local blocks 0-2 of the encoder and of the decoder recompute their
      activations in backward; block 3 of each stores them.
    - The encoder's and decoder's residual streams run in the autocast dtype,
      bfloat16. Autocast leaves the embedding tables' outputs, and so the
      streams, in float32; RMSNorm still normalizes in float32.
    - Frames and jobs are padded to multiples of 64 with inert entries, so
      compiled shapes and cuDNN attention plans repeat.
    - Validation scores ``data.EvalSpans``: 64 spans of 2,048 decisions drawn
      once from the validation split by their own seed, each after as much of
      its episode as a window holds, weighted to the natural mix. The targets
      no longer move with the window length, the GPU count, or the sampler
      seed, and ``val/bpb``, its strata, and ``nats_per_decision_natural``
      describe the natural distribution, not the sampled one.
    - The init is pinned, ``seed`` 0, so forks share it: at update 240 the init
      seed alone moved the objective more than the data order did. A seed run
      sets both ``seed`` and ``dataset.sampler_seed``.

    Hypothesis:
      The speed settings keep the loss curve within same-seed nondeterminism
      and cut the update time by about 8% on one H200, and forks at other
      window lengths or GPU counts are scored on exactly the same decisions.

    References:
      ``metric.py``: bits per byte in the natural mix, the primary metric.

    Results:
      The speed settings were measured on exp002 first (one H200, the small
      corpus, seed 0): 4.517 s per update as committed, 4.324 s with blocks
      0-2 recomputed, 4.344 s with bfloat16 local streams, 4.129 s with both
      (112.7 GB), and 4.153 s (-8.1%) over 40 updates with the padding too;
      over 240 updates the loss stayed inside the same-seed band.

      exp010 against exp002, side by side on one H200 each (the small corpus,
      40 updates): an update takes 4.126 s against 4.510 s (median of
      updates 3-40), -8.5%, and never stalls on new counts (slowest 4.25 s
      against 6.65 s), at a peak of 117.4 GB against 107.5 GB (111,921 and
      102,561 MiB in nvidia-smi). Both compile the model once, the first
      update taking 68 s and 69 s with a warm cache. The training loss at
      update 40 matches, 12.393 against 12.397. Scoring the 64 spans takes
      38 s against 22 s for exp002's 32 windows; the scores differ, as they
      are of other decisions. ``train/tok_per_sec`` and ``train/mfu`` count
      the padded frames and jobs, under 1% of either. Rerun once the local
      streams were cast only under autocast: 4.137 s, the same peak, loss
      12.393 at update 40, and validation bpb 0.84496 against 0.84493.

      The full run, one H200, the base corpus: 1,525 updates in 7,051 s,
      7,817 decisions/s, peak
      113.2 GB in nvidia-smi. At 50M decisions validation bpb_natural is
      0.00910 (bpb 0.00860, 5.66 nats per decision natural); board 0.00682,
      HUD 0.01155, action 1.142, reward 0.00113. Every loss finite, the
      attention logit bound at most 17.0, 55% of updates clipped.

    """
    cfg = exp002()
    cfg.experiment_name = "exp010"
    cfg.seed = 0
    model = cfg.step.model
    assert isinstance(model, WorldModel.Config)
    assert isinstance(model.encoder, FrameEncoder.Config)
    for stack in (model.encoder.stack, model.decoder.stack):
        template = stack.block
        assert isinstance(template, TransformerBlock.Config | DecoderBlock.Config)
        blocks = [template.copy_tree() for _ in range(stack.num_layers)]
        # Storing block 3 of each stack peaks at 120 GB of an H200's 143; storing
        # the encoder's block 2 too came within 1 GB of the card.
        blocks[-1].checkpoint = False
        stack.block = list[ChannelsInOutConfig](blocks)
    model.encoder.cast_stream = model.decoder.cast_stream = to_autocast_dtype
    cfg.dataset.count_multiple = 64
    cfg.dataset.validation = EvalSpans.Config()
    return cfg


def exp011() -> WorldModelLoop.Config:
    """exp010 with the model's three speed settings on.

    Board cells embed as one multi-hot matmul (``multi_hot_board``), every
    SwiGLU runs its gate and up halves as two matmuls, and each recomputed local
    block stores its attention outputs (``keep_attention``). The three are one
    change, measured together. The last two compute the same values; the
    multi-hot board equals the summed gathers in float32, but under the bfloat16
    autocast these experiments train in it is a bfloat16 matmul, which rounds
    differently from the float32 gather.

    Hypothesis:
      The settings cut the update time by about 8% on one H200 and keep the
      loss curve within same-seed nondeterminism, so every later fork buys more
      training per hour at no cost in NLL.

    References:
      https://arxiv.org/abs/1604.06174
        Chen et al. 2016. Training deep nets with sublinear memory cost
        (recomputation, of which keeping attention outputs is a policy).

    Results:
      One H200, the small corpus, 240 updates: 3.834 s per update against
      4.156 s (-7.7%), 8,547
      decisions/s, peak 114.1 GB against 111.9 GB; the multi-hot board alone
      gave -1.8%, the split gate -3.2%, and the kept attention -3.2% with the
      other two, for 4.7 GB more. The per-update objective differs from
      exp010's by 0.0112 on average, against 0.0097 between two exp010 runs of
      one seed and 0.157 between two data orders. Over whole 26.2M-decision
      probes at 16,384 decisions per update, three data orders with the
      settings and three without scored the same (see exp012).

    """
    cfg = exp010()
    cfg.experiment_name = "exp011"
    model = cfg.step.model
    assert isinstance(model, WorldModel.Config)
    assert isinstance(model.encoder, FrameEncoder.Config)
    model.embed_board = multi_hot_board
    for stack in (model.encoder.stack, model.decoder.stack):
        assert isinstance(stack.block, list)
        for block in stack.block:
            assert isinstance(block, (EncoderBlock.Config, DecoderBlock.Config))
            assert isinstance(block.ffn, SwiGLU.Config)
            block.ffn.split_gate_projection = True
            block.recompute_policy = keep_attention
    block = model.transformer.block
    assert isinstance(block, TransformerBlock.Config)
    assert isinstance(block.ffn, SwiGLU.Config)
    block.ffn.split_gate_projection = True
    return cfg


def exp012() -> WorldModelLoop.Config:
    """exp011 at 16,384 decisions per update: the batch sweep's value.

    Two accumulated 16K windows per update instead of four, so twice the
    updates, 3,051, over the same 50M decisions. Peak rate, warmup, and decay
    keep their fractions of the run, so warmup spans the same 5M decisions.

    Hypothesis:
      exp010 is short of updates, not of data: at 800 updates of 32,768
      decisions its validation NLL was still falling steeply into the decay,
      so twice the updates at the same decisions lowers NLL.

    References:
      https://arxiv.org/abs/1812.06162
        McCandlish et al. 2018. An empirical model of large-batch training:
        below the critical batch size, more updates of fewer samples win.

    Results:
      Tuning, one H200 per run, the base corpus: exp010's schedule compressed
      into 26.2M decisions. At the end of the decay 16,384 decisions per
      update scored val bpb_natural 0.00939 against exp010's 0.01234, -23.9%;
      three data orders of exp010 gave 0.01234, 0.01206, 0.01263 (sd 2.3%).
      HUD fell 54%, board 16%, action 4%, at the same decisions/s. At 16,384, three
      data orders with the speed flags scored 0.00994, 0.00969, 0.00977, and
      the same three orders without them 0.00939, 0.01036, 0.00965: the same
      mean. Rescored on 512 fixed validation tiles (4.19M decisions each,
      ``scripts/data_eval.py``) the flagless runs are 0.4%
      lower, board +0.1%, HUD -2.6%, within their spread; the 64 spans' HUD
      moves one run's score by up to 7%. Peak rate, against the flagged run of the same data order:
      1e-3 over three orders scored 0.00940, 0.00996, 0.00948 (-1.9%), but
      +2.4% on the tiles (board -1.1%, HUD +19%), and its training objective
      over the last 400 updates was 0.6-1.0% higher in each order; 2e-3
      scored 0.01106 (+11%); 6e-4 0.00979 (-1.6%), -2.0% on the tiles with
      board -2.0%, one order only. At 8,192 decisions per update, with the
      flags, 0.00885, 0.00918, 0.00914: 7.6% below the flagged 16K runs and
      lower in each data order.

      At 50M decisions, beside exp010: val bpb_natural 0.00824 against
      exp010's 0.00910, -9.4%
      (5.13 against 5.66 nats per decision natural); HUD -43%, board -6%,
      action -1.5%. The gap was -4.0% where the decay began, at 45M
      decisions, and -9.4% where it ended. 3,051 updates in 6,593 s against
      7,051 s, 8,358 decisions/s, peak 109.7 GB; the attention logit bound
      at most 15.8, 43% of updates clipped. Fidelity suite at 50M against
      exp010's: teacher-forced NLL -0.40 nats per decision (lower on 124 of
      128 spans), HUD values over their maxima in dreams -31 and
      inconsistent moves -13 per 1,000 decisions; continuations of real
      prefixes under the recorded actions no different (board mismatch at
      128 decisions +0.04, 95% interval -0.03 to +0.12; 58 against 55 of 64
      windows ended in a death, real 16). At 26.2M decisions the 16K probe
      had ended 54 against 28 to 35 for three data orders of exp010; that
      count rises with training for both, exp010 reaching 55 at 50M.

    """
    cfg = exp011()
