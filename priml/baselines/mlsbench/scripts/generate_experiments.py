r"""Generate one experiment function per (task, baseline, seed) from ``registry.json``.

Generating reads the committed registry only, never the upstream clone, so it
runs anywhere. Each task gets its own module, ``tasks/<task_module>.py`` (the
task name with ``-`` replaced by ``_``), so a task is addressed on its own the
way every other priml baseline is. Functions are numbered ``exp000``... locally
per task in ``(registry baseline order, seed)`` order, so adding a task never
renumbers another one. Each module's ``INDEX`` maps a function name to its
``(task, baseline, seed)``, and ``list`` prints the exact dotted path of every
experiment::

    uv --quiet run --frozen python -m priml.baselines.mlsbench.scripts.generate_experiments list [--task T]
    uv --quiet run --frozen python -m priml.baselines.mlsbench.scripts.generate_experiments --check
    uv --quiet run --frozen python -m priml.baselines.mlsbench.scripts.generate_experiments --write
    uv --quiet run --frozen python -m priml.baselines.mlsbench.scripts.generate_experiments --registry [--root DIR]

``--check`` writes nothing and exits 1 when a generated file is stale, missing
or stray. ``--registry`` is the one step that reads a clone (``/opt/scratch/mlsbench``
unless ``--root`` says otherwise): it rewrites ``registry.json`` after a deliberate
upstream bump, then ``--write`` regenerates the modules from it.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Final, Protocol, cast

import argparse
import json
import keyword
import sys
import textwrap

from priml.baselines.mlsbench import tasks
from priml.baselines.mlsbench.experiments import TaskEntry
from priml.baselines.mlsbench.scripts.prepare_data import UPSTREAM_DIR, default_path
from priml.baselines.mlsbench.task import load_all


if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

    from priml.baselines.mlsbench.task import TaskSpec


PKG: Final = Path(__file__).resolve().parent.parent
"""The ``priml/baselines/mlsbench`` directory."""

REGISTRY_PATH: Final = PKG / "registry.json"
TASKS_DIR: Final = PKG / "tasks"
MODULE_PREFIX: Final = "priml.baselines.mlsbench.tasks"
HEADER: Final = "# GENERATED by scripts/generate_experiments.py; do not edit.\n"
WIDTH: Final = 88
UPSTREAM_PIN: Final = "80cf5c5c"
"""The upstream MLS-Bench commit ``registry.json`` was read from."""

Row = tuple[str, str, int]
"""One experiment: (task, baseline, seed)."""


def _entry(task: TaskSpec) -> TaskEntry:
    return TaskEntry(
        baselines=tuple(b.name for b in task.baselines),
        settings={s.label: s.time_limit for s in task.settings},
        seeds=tuple(task.seeds),
        hidden=tuple(s.label for s in task.settings if s.hidden),
    )


def registry_from_clone(root: Path) -> dict[str, TaskEntry]:
    """Read every task of an upstream clone (strict parse), sorted by name.

    Args:
      root: The upstream clone.

    Returns:
      tasks: Task name to its :class:`TaskEntry`.

    """
    return {t.name: _entry(t) for t in load_all(Path(root))}


def write_registry(root: Path, path: Path = REGISTRY_PATH) -> int:
    """Regenerate the committed snapshot from a clone; returns the task count."""
    reg = registry_from_clone(root)
    doc = {
        name: {
            "baselines": list(e.baselines),
            "settings": dict(e.settings),
            "seeds": list(e.seeds),
            "hidden": list(e.hidden),
        }
        for name, e in reg.items()
    }
    _ = path.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    return len(doc)


def module_of(task: str) -> str:
    """Return the module name of ``task`` (``-`` replaced by ``_``).

    Raises:
      ValueError: The result is not a lowercase identifier.

    """
    mod = tasks.module_of(task)
    if not mod.isidentifier() or not mod.islower() or keyword.iskeyword(mod):
        raise ValueError(f"task {task!r}: {mod!r} is not a module name")
    return mod


def load_registry(path: Path = REGISTRY_PATH) -> dict[str, dict[str, object]]:
    """Read ``registry.json`` as plain JSON (no priml imports)."""
    return cast("dict[str, dict[str, object]]", json.loads(path.read_text()))


def plan(registry: Mapping[str, Mapping[str, object]]) -> dict[str, list[Row]]:
    """Return task module name to its ordered experiment rows.

    Rows sort by ``(registry baseline order, seed)``; a task without ``seeds``
    runs the upstream default, seed 42.

    Raises:
      ValueError: Two task names map to the same module name.

    """
    mods: dict[str, list[Row]] = {}
    for task in sorted(registry):
        mod = module_of(task)
        if mod in mods:
            raise ValueError(f"tasks {mods[mod][0][0]!r} and {task!r} share {mod!r}")
        entry = registry[task]
        seeds = sorted(cast("list[int]", entry.get("seeds") or [42]))
        mods[mod] = [
            (task, str(b), s)
            for b in cast("list[str]", entry["baselines"])
            for s in seeds
        ]
    return dict(sorted(mods.items()))


def _lit(s: str) -> str:
    return json.dumps(s)


def _wrap(head: str, args: Sequence[str], tail: str, indent: str) -> list[str]:
    """Lines for ``head(args)tail``: one line if it fits, else one arg per line."""
    one = f"{indent}{head}({', '.join(args)}){tail}"
    if len(one) <= WIDTH:
        return [one]
    return [
        f"{indent}{head}(",
        *(f"{indent}    {a}," for a in args),
        f"{indent}){tail}",
    ]


def _para(text: str) -> list[str]:
    """Wrap ``text`` as a docstring section body (six-space indent)."""
    return textwrap.wrap(
        text,
        WIDTH,
        initial_indent="      ",
        subsequent_indent="      ",
        break_long_words=False,
        break_on_hyphens=False,
    )


def _describe(entry: Mapping[str, object]) -> list[str]:
    """Docstring body lines naming the task's baselines, settings and seeds."""
    hidden = set(cast("list[str]", entry.get("hidden") or []))
    settings = cast("Mapping[str, float]", entry["settings"])
    seeds = sorted(cast("list[int]", entry.get("seeds") or [42]))
    lines = [
        "One function per (baseline, seed), numbered in the task's baseline order.",
        "Each applies that baseline's edit and runs every setting of the task in",
        "its pinned image.",
        "",
        *textwrap.wrap(
            "Baselines: "
            + ", ".join(f"``{b}``" for b in cast("list[str]", entry["baselines"]))
            + ".",
            WIDTH,
            break_long_words=False,
            break_on_hyphens=False,
        ),
        "Seeds: " + ", ".join(str(s) for s in seeds) + ".",
        "Settings (time limit; hidden settings are hidden from an agent, and run):",
        "",
    ]
    for label in sorted(settings):
        mark = ", hidden" if label in hidden else ""
        lines.append(f"- ``{label}``: {settings[label]:g} s{mark}")
    return lines


def render(rows: Sequence[Row], entry: Mapping[str, object]) -> str:
    """Return the source of one task's module: its ``rows`` and registry ``entry``."""
    task = rows[0][0]
    out = [
        HEADER,
        f'"""Generated MLS-Bench experiments of task ``{task}`` ({len(rows)}).\n',
        *_describe(entry),
        "",
        "Written by ``scripts/generate_experiments.py`` from ``registry.json``.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import TYPE_CHECKING, Final",
        "",
        "from priml.baselines.mlsbench.experiments import mlsbench_experiment",
        "",
        "",
        "if TYPE_CHECKING:",
        "    from priml.baselines.mlsbench.experiments import MlsbenchEval",
        "",
    ]
    for i, (task, baseline, seed) in enumerate(rows):
        out += [
            "",
            f"def exp{i:03d}() -> MlsbenchEval:",
            '    """Reproduce one MLS-Bench baseline row.',
            "",
            f"    Task ``{task}``, baseline ``{baseline}``, seed {seed}.",
            "",
            "    Hypothesis:",
            *_para(
                "The published row is reproduced within the leaderboard's tolerance:"
                " the same edit, run by the same scripts in the same pinned image.",
            ),
            "",
            "    Returns:",
            "      cfg: The eval-only loop config.",
            "",
            "    References:",
            *_para(
                f"MLS-Bench ``tasks/{task}/leaderboard.csv``, row"
                f" ``baseline:{baseline}``, seed {seed} (upstream ``{UPSTREAM_PIN}``).",
            ),
            "",
            "    Results:",
            "      TBD.",
            "",
            '    """',
            *_wrap(
                "return mlsbench_experiment",
                [_lit(task), _lit(baseline), f"seed={seed}"],
                "",
                "    ",
            ),
            "",
        ]
    out += [
        "",
        "INDEX: Final[dict[str, tuple[str, str, int]]] = {",
    ]
    for i, (task, baseline, seed) in enumerate(rows):
        out += _index_entry(i, task, baseline, seed)
    out += ["}", '"""Function name to (task, baseline, seed)."""', ""]
    return "\n".join(out)


def _index_entry(i: int, task: str, baseline: str, seed: int) -> list[str]:
    key = f'"exp{i:03d}"'
    one = f"    {key}: ({_lit(task)}, {_lit(baseline)}, {seed}),"
    if len(one) <= WIDTH:
        return [one]
    return [
        f"    {key}: (",
        f"        {_lit(task)},",
        f"        {_lit(baseline)},",
        f"        {seed},",
        "    ),",
    ]


def generate(
    registry: Mapping[str, Mapping[str, object]] | None = None,
) -> dict[Path, str]:
    """Return every generated file's path to its exact contents."""
    reg = load_registry() if registry is None else registry
    return {
        TASKS_DIR / f"{m}.py": render(rows, reg[rows[0][0]])
        for m, rows in plan(reg).items()
    }


def stale(files: Mapping[Path, str]) -> list[str]:
    """Return human-readable problems between ``files`` and the tree (empty = fresh)."""
    problems: list[str] = []
    for path, text in files.items():
        if not path.exists():
            problems.append(f"missing {path.name}")
        elif path.read_text() != text:
            problems.append(f"stale {path.name}")
    problems.extend(
        f"stray {p.name}"
        for p in sorted(TASKS_DIR.glob("*.py"))
        if p.name != "__init__.py" and p not in files
    )
    return problems


def write(files: Mapping[Path, str]) -> None:
    """Write ``files`` and remove stray generated modules."""
    TASKS_DIR.mkdir(exist_ok=True)
    for path, text in files.items():
        _ = path.write_text(text)
    for p in TASKS_DIR.glob("*.py"):
        if p.name != "__init__.py" and p not in files:
            p.unlink()


def list_rows(
    registry: Mapping[str, Mapping[str, object]] | None = None,
    *,
    task: str | None = None,
) -> list[str]:
    """Return ``dotted.path  task  baseline  seed`` lines, optionally for one task."""
    reg = load_registry() if registry is None else registry
    return [
        f"{MODULE_PREFIX}.{mod}.exp{i:03d}  {t}  {b}  {s}"
        for mod, rows in plan(reg).items()
        for i, (t, b, s) in enumerate(rows)
        if task is None or t == task
    ]


class _Flags(Protocol):
    command: str | None
    check: bool
    write: bool
    task: str | None
    registry: bool
    root: str


def main(argv: Sequence[str] | None = None) -> int:
    """Run ``--check`` (default), ``--write``, ``--registry`` or ``list``; returns the exit code."""
    p = argparse.ArgumentParser(
        description="Generate the MLS-Bench experiment modules.",
    )
    _ = p.add_argument("command", nargs="?", choices=["list"])
    _ = p.add_argument("--check", action="store_true")
    _ = p.add_argument("--write", action="store_true")
    _ = p.add_argument("--task")
    _ = p.add_argument(
        "--registry",
        action="store_true",
        help="rewrite registry.json from the clone at --root",
    )
    _ = p.add_argument("--root", default=str(default_path(UPSTREAM_DIR)))
    ns = cast("_Flags", p.parse_args(argv))
    if ns.registry:
        print(f"wrote {write_registry(Path(ns.root))} tasks to {REGISTRY_PATH}")
        return 0
    if ns.command == "list":
        for line in list_rows(task=ns.task):
            print(line)
        return 0
    files = generate()
    if ns.write:
        write(files)
        print(f"wrote {len(files)} modules")
        return 0
    problems = stale(files)
    for line in problems:
        print(line)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
