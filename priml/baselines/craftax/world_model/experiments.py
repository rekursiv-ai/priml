"""World-model experiments: the base model, the smoke run, and the flat comparison.

``exp000`` is the base: the hierarchical world model (encoder, ~283M global
transformer, local decoder), Muon on hidden matrices and AdamW on the rest,
warmup-stable-decay, 8 windows of 8,192 global positions per step on 8 GPUs,
trained on the frozen base corpus for 50M decisions. It is never edited. Every
later experiment forks a named parent with exactly one change -- sweeps of the
recipe's values first, then established practice, nanochat's techniques and
structure -- so the chain reads as an argument::

    exp000     the base model, 50M decisions of the base corpus
    exp001     exp000 on one GPU: the same 8-window update, accumulated
    exp002     exp001 with 16,384-position windows, 4 per update
    exp010     exp002 as the tuning base: speed settings, natural validation
    exp011     exp010 with the model's three speed settings
    exp012     exp011 at 16,384 decisions per update
    exp013     exp012 at 8,192 decisions per update, one window each
    exp014     exp013 on replay shards, its frames regenerated by replay
    exp015     exp014 with the grid convolution frame encoder
    exp020     exp013 five times larger on 8 GPUs, trained open-ended
    exp_smoke  exp000 at minimum size on the CPU; not a result

The base corpus is ``corpora/base.json`` of the capture archive ``archive-v1``
beneath ``/datasets/craftax/world-model``: the arms of ``capture.experiments``
capture it, and ``scripts/freeze_corpus.py`` freezes 50M of its training
decisions. The recorded results were measured on the original implementation's
capture of the same mixture.

The flat comparison trains on the frozen small corpus, 10M decisions of an
earlier capture::

    exp003     the flat model: every slot one global position
    exp004     exp001 at exp003's training FLOPs
    exp005     exp004's final weights scored on exp003's validation windows

Every run logs nanochat's series: ``train/loss``, ``train/lrm``,
``train/dt``, ``train/tok_per_sec``, ``train/mfu``, ``total_training_flops``,
``total_training_time``, ``val/bpb``, and its modality and stratum splits. Its
W&B run is named after the experiment, and its seed when one is set, and
grouped by experiment, unless the tracker names them.

Launch on one 8-GPU node, or ``exp001`` on one GPU::

    uv --quiet run --frozen python -m torch.distributed.run --standalone --nproc_per_node=8 -m priml priml.baselines.craftax.world_model.experiments.exp000
    uv --quiet run --frozen python -m priml priml.baselines.craftax.world_model.experiments.exp001
"""

